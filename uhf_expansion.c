static uint32_t uhf_read_be(const uint8_t* data, size_t len) {
    uint32_t value = 0;
    for(size_t i = 0; i < len; i++) {
        value = (value << 8) | data[i];
    }
    return value;
}

static bool uhf_bytes_to_hex(const uint8_t* data, size_t len, char* out, size_t out_size) {
    if(out_size < (len * 2 + 1)) return false;

    for(size_t i = 0; i < len; i++) {
        snprintf(&out[i * 2], 3, "%02X", data[i]);
    }
    out[len * 2] = '\0';
    return true;
}

static bool uhf_is_valid_epc(const uint8_t* epc, size_t epc_len) {
    static const uint8_t reader_placeholder[] = {0xE2U, 0x80U, 0x69U, 0x00U, 0x00U};

    if(!epc || epc_len < 4U || epc_len > (UHF_EPC_HEX_MAX / 2U)) return false;

    bool nonzero = false;
    for(size_t i = 0; i < epc_len; i++) {
        if(epc[i] != 0U) {
            nonzero = true;
            break;
        }
    }

    return nonzero &&
           !(epc_len >= sizeof(reader_placeholder) &&
             memcmp(epc, reader_placeholder, sizeof(reader_placeholder)) == 0);
}

static UhfTagEntry* uhf_find_or_add_tag(UhfApp* app, const char* epc_hex, bool* is_new_tag) {
    const uint32_t now = furi_get_tick();

    for(size_t i = 0; i < UHF_MAX_TAGS; i++) {
        if(app->tags[i].used && strcmp(app->tags[i].epc, epc_hex) == 0) {
            /* Deduplicate: if this same EPC was seen very recently, don't count as new */
            const bool recent = (now - app->tags[i].last_seen) < 800U;
            if(is_new_tag) *is_new_tag = !recent;
            return &app->tags[i];
        }
    }

    for(size_t i = 0; i < UHF_MAX_TAGS; i++) {
        if(!app->tags[i].used) {
            app->tags[i].read_count = 0;
            app->tags[i].rssi = 0;
            app->tags[i].frequency = 0;
            app->tags[i].antenna = 0;
            strncpy(app->tags[i].epc, epc_hex, sizeof(app->tags[i].epc) - 1);
            app->tags[i].epc[sizeof(app->tags[i].epc) - 1] = '\0';
            app->tags[i].used = true;
            app->tags[i].last_seen = 0; /* will be set by caller */
            app->tag_count++;
            if(is_new_tag) *is_new_tag = true;
            return &app->tags[i];
        }
    }

    return NULL;
}

static bool uhf_build_frame(
    uint8_t cmd,
    const uint8_t* payload,
    size_t payload_len,
    uint8_t* out,
    size_t out_size,
    size_t* frame_size) {
    const size_t len_field = payload_len + 3U;
    const size_t total_size = len_field + 2U;
    if(total_size > out_size || len_field > UINT8_MAX) return false;

    out[0] = UHF_FRAME_START;
    out[1] = (uint8_t)len_field;
    out[2] = UHF_DEFAULT_ADDR;
    out[3] = cmd;
    if(payload_len) {
        memcpy(&out[4], payload, payload_len);
    }

    uint32_t checksum_acc = 0;
    for(size_t i = 0; i < total_size - 1U; i++) {
        checksum_acc = (checksum_acc + out[i]) & 0xFFU;
    }
    out[total_size - 1U] = (uint8_t)((~checksum_acc + 1U) & 0xFFU);

    *frame_size = total_size;
    return true;
}

static bool uhf_send_raw_frame(UhfApp* app, const uint8_t* frame, size_t frame_size) {
    if(!frame || frame_size < 5U) return false;
    if(!app->serial) return false;

    furi_hal_serial_tx(app->serial, frame, frame_size);
    furi_hal_serial_tx_wait_complete(app->serial);

    char hex[49] = "";
    const size_t shown = frame_size > 24U ? 24U : frame_size;
    if(uhf_bytes_to_hex(frame, shown, hex, sizeof(hex))) {
        uhf_diag_log(app, "TX len=%lu %s", (unsigned long)frame_size, hex);
        if(frame[3] == UHF_CMD_READ_TAG || frame[3] == UHF_CMD_WRITE_TAG ||
           frame[3] == UHF_CMD_SET_EPC_MATCH) {
            FURI_LOG_I(TAG, "Tag TX %s", hex);
        }
    }

    return true;
}

static void uhf_store_last_rx_hex(UhfApp* app, const uint8_t* frame, size_t frame_size) {
    const size_t shown = frame_size > 20U ? 20U : frame_size;
    (void)uhf_bytes_to_hex(frame, shown, app->last_rx_hex, sizeof(app->last_rx_hex));
}

static bool uhf_send_command(UhfApp* app, uint8_t cmd, const uint8_t* payload, size_t payload_len) {
    uint8_t frame[272];
    size_t frame_size = 0;
    if(!uhf_build_frame(cmd, payload, payload_len, frame, sizeof(frame), &frame_size)) {
        return false;
    }

    return uhf_send_raw_frame(app, frame, frame_size);
}

static const char* uhf_tag_error_text(uint8_t code) {
    switch(code) {
    case 0x10: return "OK";
    case 0x20: return "No tag";
    case 0x22: return "Wrong password";
    case 0x23: return "Memory overrun";
    case 0x24: return "Memory locked";
    case 0x31: return "Access failed";
    case 0x32: return "Read failed";
    case 0x33: return "Write failed";
    default: return "Tag operation failed";
    }
}

static bool uhf_wait_tag_reply(
    UhfApp* app,
    uint8_t cmd,
    const uint8_t* payload,
    size_t payload_len,
    uint32_t timeout_ms) {
    app->tag_reply_ready = false;
    app->tag_reply_len = 0U;
    app->tag_reply_cmd = cmd;
    if(!uhf_send_command(app, cmd, payload, payload_len)) return false;

    const uint32_t started = furi_get_tick();
    while((furi_get_tick() - started) < timeout_ms) {
        uhf_process_rx(app);
        if(app->tag_reply_ready && app->tag_reply_cmd == cmd) {
            return app->tag_reply_checksum_ok;
        }
        furi_delay_ms(5U);
    }
    uhf_set_status(app, "Reader timeout (0x%02X)", cmd);
    return false;
}

static bool uhf_hex_to_bytes(const char* hex, uint8_t* out, size_t out_size, size_t* out_len) {
    if(!hex || !out || !out_len) return false;
    const size_t hex_len = strlen(hex);
    if((hex_len & 1U) || hex_len / 2U > out_size) return false;

    for(size_t i = 0U; i < hex_len / 2U; i++) {
        unsigned int value = 0U;
        if(sscanf(&hex[i * 2U], "%2x", &value) != 1) return false;
        out[i] = (uint8_t)value;
    }
    *out_len = hex_len / 2U;
    return true;
}

static bool uhf_set_selected_epc_filter(UhfApp* app) {
    uint8_t epc[UHF_EPC_HEX_MAX / 2U];
    size_t epc_len = 0U;
    if(!uhf_hex_to_bytes(app->access_epc, epc, sizeof(epc), &epc_len) || epc_len == 0U) {
        uhf_set_status(app, "Invalid selected EPC");
        return false;
    }

    uint8_t payload[2U + UHF_EPC_HEX_MAX / 2U];
    payload[0] = 0x00U;
    payload[1] = (uint8_t)epc_len;
    memcpy(&payload[2], epc, epc_len);
    if(!uhf_wait_tag_reply(app, UHF_CMD_SET_EPC_MATCH, payload, epc_len + 2U, 1200U)) {
        uhf_set_status(app, "EPC filter timeout");
        return false;
    }
    if(app->tag_reply_len != 1U || app->tag_reply[0] != 0x10U) {
        const uint8_t code = app->tag_reply_len ? app->tag_reply[0] : 0xFFU;
        uhf_set_status(app, "Filter error 0x%02X", code);
        return false;
    }
    app->epc_filter_active = true;
    return true;
}

static void uhf_clear_selected_epc_filter(UhfApp* app) {
    if(!app || !app->epc_filter_active) return;
    const uint8_t clear_mode = 0x01U;
    (void)uhf_wait_tag_reply(app, UHF_CMD_SET_EPC_MATCH, &clear_mode, 1U, 600U);
    app->epc_filter_active = false;
}

static bool uhf_read_selected_bank_words(
    UhfApp* app,
    uint8_t memory_bank,
    uint8_t word_address,
    uint8_t word_count,
    char* out,
    size_t out_size,
    const char* name,
    bool use_epc_filter) {
    if(use_epc_filter && !app->epc_filter_active && !uhf_set_selected_epc_filter(app)) {
        return false;
    }

    out[0] = '\0';

    /* Newer UCM601NC firmware uses a 32-bit word address and 16-bit word count. */
    uint8_t payload[] = {
        memory_bank,
        0x00U, 0x00U, 0x00U, 0x00U,
        0x00U, word_count,
        0x00U, 0x00U, 0x00U, 0x00U,
    };
    payload[4] = word_address;
    uhf_set_status(app, "Reading %s...", name);
    if(!uhf_wait_tag_reply(app, UHF_CMD_READ_TAG, payload, sizeof(payload), 2500U)) return false;
    if(app->tag_reply_len == 1U) {
        uhf_set_status(app, "Error 0x%02X", app->tag_reply[0]);
        return false;
    }
    if(app->tag_reply_len < 6U) {
        uhf_set_status(app, "Malformed %s reply", name);
        return false;
    }

    const size_t record_len = app->tag_reply[2];
    const size_t record_end = 3U + record_len;
    if(record_end + 3U > app->tag_reply_len) {
        uhf_set_status(app, "Malformed %s record", name);
        return false;
    }
    size_t read_len = app->tag_reply[record_end];
    /* Extended firmware returns ReadLen as a 16-bit big-endian value. */
    if(record_end + 4U <= app->tag_reply_len) {
        const size_t extended_len =
            ((size_t)app->tag_reply[record_end] << 8U) | app->tag_reply[record_end + 1U];
        if(extended_len > 0U && extended_len <= record_len) read_len = extended_len;
    }
    if(read_len == 0U || read_len * 2U + 1U > out_size || read_len > record_len) {
        uhf_set_status(app, "Invalid %s length", name);
        return false;
    }
    const uint8_t* value = &app->tag_reply[record_end - read_len];
    if(!uhf_bytes_to_hex(value, read_len, out, out_size)) {
        uhf_set_status(app, "%s too long", name);
        return false;
    }
    uhf_set_status(app, "%s read: %lu bytes", name, (unsigned long)read_len);
    return true;
}

static bool uhf_read_selected_tid(UhfApp* app) {
    /* Six words covers the common 96-bit serialized TID. */
    app->selected_tid_valid = uhf_read_selected_bank_words(
        app,
        0x02U,
        0x00U,
        6U,
        app->selected_tid,
        sizeof(app->selected_tid),
        "TID",
        !app->tag_access_unfiltered);
    return app->selected_tid_valid;
}

static bool uhf_read_selected_user(UhfApp* app) {
    app->selected_user_valid = uhf_read_selected_bank_words(
        app,
        0x03U,
        0x00U,
        16U,
        app->selected_user,
        sizeof(app->selected_user),
        "USER",
        !app->tag_access_unfiltered);
    return app->selected_user_valid;
}

static const char* uhf_tag_bank_name(UhfTagBank bank) {
    if(bank == UhfTagBankTid) return "TID";
    if(bank == UhfTagBankUser) return "User Data";
    return "EPC";
}

static bool uhf_write_selected_bank(UhfApp* app, UhfTagBank bank, const char* value_hex) {
    uint8_t value[UHF_USER_HEX_MAX / 2U];
    size_t value_len = 0U;
    const char* name = uhf_tag_bank_name(bank);
    if(!uhf_hex_to_bytes(value_hex, value, sizeof(value), &value_len) || !value_len ||
       (value_len & 1U)) {
        uhf_set_status(app, "%s must be whole words", name);
        uhf_notify_write_result(app, false);
        return false;
    }

    /* The user may replace the source tag with a writable target. Access must
       therefore be unfiltered and only one target tag should be in the field. */
    uhf_clear_selected_epc_filter(app);
    app->tag_access_unfiltered = true;
    furi_delay_ms(UHF_STOP_SETTLE_MS);

    uint8_t payload[11U + UHF_USER_HEX_MAX / 2U] = {0};
    payload[4] = (bank == UhfTagBankEpc) ? 0x01U : (bank == UhfTagBankTid ? 0x02U : 0x03U);
    payload[8] = (bank == UhfTagBankEpc) ? 0x02U : 0x00U;
    payload[10] = (uint8_t)(value_len / 2U);
    memcpy(&payload[11], value, value_len);
    uhf_set_status(app, "Writing %s...", name);
    if(!uhf_wait_tag_reply(app, UHF_CMD_WRITE_TAG, payload, 11U + value_len, 3000U)) {
        uhf_notify_write_result(app, false);
        return false;
    }

    uint8_t status = 0xFFU;
    if(app->tag_reply_len == 1U) {
        status = app->tag_reply[0];
    } else if(app->tag_reply_len >= 6U) {
        const size_t record_end = 3U + app->tag_reply[2];
        if(record_end < app->tag_reply_len) status = app->tag_reply[record_end];
    }
    if(status != 0x10U) {
        uhf_set_status(app, "%s write: %s", name, uhf_tag_error_text(status));
        uhf_notify_write_result(app, false);
        return false;
    }

    char verify[UHF_USER_HEX_MAX + 1U] = "";
    if(!uhf_read_selected_bank_words(
                  app,
                  bank == UhfTagBankEpc ? 0x01U : (bank == UhfTagBankTid ? 0x02U : 0x03U),
                  bank == UhfTagBankEpc ? 0x02U : 0x00U,
                  (uint8_t)(value_len / 2U),
                  verify,
                  sizeof(verify),
                  name,
                  false)) {
        uhf_set_status(app, "Write OK; verify failed");
        uhf_notify_write_result(app, false);
        return true;
    }
    if(strcmp(verify, value_hex) != 0) {
        uhf_set_status(app, "Verify mismatch");
        uhf_notify_write_result(app, false);
        return false;
    }
    if(bank == UhfTagBankEpc) {
        strncpy(app->selected_epc, verify, sizeof(app->selected_epc) - 1U);
        app->selected_epc[sizeof(app->selected_epc) - 1U] = '\0';
        strncpy(app->access_epc, verify, sizeof(app->access_epc) - 1U);
        app->access_epc[sizeof(app->access_epc) - 1U] = '\0';
    } else if(bank == UhfTagBankTid) {
        strncpy(app->selected_tid, verify, sizeof(app->selected_tid) - 1U);
        app->selected_tid[sizeof(app->selected_tid) - 1U] = '\0';
        app->selected_tid_valid = true;
    } else if(bank == UhfTagBankUser) {
        strncpy(app->selected_user, verify, sizeof(app->selected_user) - 1U);
        app->selected_user[sizeof(app->selected_user) - 1U] = '\0';
        app->selected_user_valid = true;
    }
    uhf_set_status(app, "%s write verified", name);
    uhf_notify_write_result(app, true);
    return true;
}

static bool uhf_ensure_hardware(UhfApp* app) {
    /* hardware_ready means the UART is configured. Reader presence is tracked
       independently by the version response. */
    if(app->hardware_ready && app->serial) return true;

    const uint32_t desired_baud = app->baud_rate;

    if(!app->serial) {
        uhf_force_direct_a6_a4(app);
    }
    if(!app->serial) {
        uhf_set_status(app, "UART 13/14 open failed");
        return false;
    }

    app->hardware_ready = true;

    bool probe_ok = false;
    if(desired_baud != 0U) {
        probe_ok = uhf_probe_current_serial(app, desired_baud);
    }
    if(!probe_ok) {
        probe_ok = uhf_probe_current_serial(app, UHF_BAUD_RATE);
    }

    uhf_diag_log(
        app,
        "HW ready TX:%d RX:%d probe=%s",
        app->tx_ext_pin,
        app->rx_ext_pin,
        probe_ok ? "ok" : "fail");
    return true;
}

static void uhf_apply_baud(UhfApp* app, uint32_t baud_rate) {
    app->baud_rate = baud_rate;
    if(!app->serial) return;

    if(app->inventory_running) {
        app->inventory_running = false;
        (void)uhf_send_command(app, UHF_CMD_STOP_INV, NULL, 0);
    }

    furi_hal_serial_async_rx_stop(app->serial);
    furi_hal_serial_set_br(app->serial, baud_rate);
    furi_hal_serial_async_rx_start(app->serial, uhf_on_rx_irq, app, true);

    app->frame_buffer_len = 0;
    if(app->rx_stream) {
        (void)furi_stream_buffer_reset(app->rx_stream);
    }
    uhf_set_status(app, "Baud: %lu", (unsigned long)baud_rate);
}
static void uhf_stop_inventory(UhfApp* app) {
    static const uint8_t stop_frame[] = {0xA0, 0x03, 0x00, 0x8C, 0xD1};
    app->inventory_running = false;
    app->tags_per_second = 0;
    app->rate_window_reads = 0;
    app->rate_window_started = furi_get_tick();
    app->radar_step_tick = furi_get_tick();
    app->last_inv_session_tick = 0U;
    if(app->hardware_ready) {
        (void)uhf_send_raw_frame(app, stop_frame, sizeof(stop_frame));
    }
}

static bool uhf_wait_for_reader_query(UhfApp* app, bool* pending) {
    const uint32_t started = furi_get_tick();
    while(*pending && (furi_get_tick() - started) < UHF_READER_QUERY_TIMEOUT_MS) {
        uhf_process_rx(app);
        if(*pending) furi_delay_ms(5U);
    }

    if(*pending) {
        *pending = false;
        return false;
    }
    return true;
}

static bool uhf_query_reader_temperature(UhfApp* app, bool wait_for_response) {
    app->temperature_query_pending = true;
    if(!uhf_send_command(app, UHF_CMD_GET_TEMP, NULL, 0U)) {
        app->temperature_query_pending = false;
        return false;
    }

    app->last_temperature_query_tick = furi_get_tick();
    return !wait_for_response ||
           uhf_wait_for_reader_query(app, &app->temperature_query_pending);
}

static bool uhf_query_reader_power(UhfApp* app, bool wait_for_response) {
    app->power_query_pending = true;
    if(!uhf_send_command(app, UHF_CMD_GET_POWER, NULL, 0U)) {
        app->power_query_pending = false;
        return false;
    }

    return !wait_for_response || uhf_wait_for_reader_query(app, &app->power_query_pending);
}

static void uhf_start_inventory(UhfApp* app) {
    static const uint8_t start_frame[] = {0xA0, 0x04, 0x00, 0x89, 0x01, 0xD2};
    if(!uhf_ensure_hardware(app)) return;

    if(!uhf_has_version(app)) {
        uhf_set_status(app, "Connecting reader...");
        bool reader_ok = uhf_try_reader_handshake(app, 2U);
        if(!reader_ok && uhf_recover_reader(app)) {
            reader_ok = uhf_try_reader_handshake(app, 5U);
        }
        if(!reader_ok) {
            uhf_set_status(app, "Not Ready");
            return;
        }
    }

    /* Read reader telemetry while RF inventory is idle so the replies cannot
       compete with a burst of tag reports. A missing reply does not prevent
       inventory from starting; the radar keeps the last valid value. */
    (void)uhf_query_reader_temperature(app, true);
    (void)uhf_query_reader_power(app, true);

    (void)furi_stream_buffer_reset(app->rx_stream);
    app->frame_buffer_len = 0;
    const bool sent = uhf_send_raw_frame(app, start_frame, sizeof(start_frame));
    uhf_process_rx(app);

    if(sent) {
        app->inventory_running = true;
        app->tags_per_second = 0;
        app->rate_window_reads = 0;
        app->rate_window_started = furi_get_tick();
        app->radar_step_tick = furi_get_tick();
        app->last_inv_refresh_tick = furi_get_tick();
        app->last_inv_session_tick = app->last_inv_refresh_tick;
        uhf_set_status(app, "Inventory running");
    } else {
        uhf_set_status(app, "Start inventory failed");
    }
}

static bool uhf_try_reader_handshake(UhfApp* app, uint8_t attempts) {
    if(!app || attempts == 0U) return false;

    for(uint8_t attempt = 0U; attempt < attempts; attempt++) {
        uhf_request_version(app);
        if(uhf_wait_for_version(app, UHF_PROBE_TIMEOUT_MS)) {
            app->baud_probed = true;
            return true;
        }
    }
    return false;
}

static bool uhf_recover_reader(UhfApp* app) {
    if(!app || !app->serial) return false;

    uhf_stop_inventory(app);
    furi_delay_ms(UHF_STOP_SETTLE_MS);
    if(app->rx_stream) furi_stream_buffer_reset(app->rx_stream);
    app->frame_buffer_len = 0U;

    static const uint8_t reset_frame[] = {0xA0, 0x03, 0x00, UHF_CMD_RESET, 0xED};
    if(!uhf_send_raw_frame(app, reset_frame, sizeof(reset_frame))) return false;

    uhf_diag_log(app, "Reader reset sent");
    furi_delay_ms(UHF_RESET_SETTLE_MS);
    uhf_process_rx(app);
    if(app->rx_stream) furi_stream_buffer_reset(app->rx_stream);
    app->frame_buffer_len = 0U;
    uhf_clear_version(app);
    return true;
}

static void uhf_release_reset_pin(void) {
    furi_hal_gpio_init_simple(&gpio_ext_pc0, GpioModeAnalog);
}

static void uhf_hardware_reset_reader(UhfApp* app) {
    /* Hardware revision 2 connects UCM601NC RST (active low) to Flipper C0,
       external header pin 16. Keep it driven high after the pulse so the
       reader cannot drift back into reset. On revision 1 C0 is unconnected,
       making this sequence harmless. */
    furi_hal_gpio_write(&gpio_ext_pc0, true);
    furi_hal_gpio_init_simple(&gpio_ext_pc0, GpioModeOutputPushPull);
    furi_delay_ms(2U);
    furi_hal_gpio_write(&gpio_ext_pc0, false);
    furi_delay_ms(UHF_RESET_LOW_MS);
    furi_hal_gpio_write(&gpio_ext_pc0, true);
    furi_delay_ms(UHF_RESET_BOOT_MS);
    if(app) {
        uhf_diag_log(app, "Hardware reset C0/pin %u", (unsigned)UHF_RESET_EXT_PIN);
    }
}

static bool uhf_power_cycle_reader(UhfApp* app) {
    if(!app || app->hard_reset_attempted) return false;
    app->hard_reset_attempted = true;

    if(app->serial) uhf_close_serial(app);
    app->hardware_ready = false;

    Storage* storage = furi_record_open(RECORD_STORAGE);
    if(!storage) {
        uhf_diag_log(app, "Hard reset: storage unavailable");
        return false;
    }

    const FS_Error unmount_error = storage_sd_unmount(storage);
    if(unmount_error != FSE_OK && unmount_error != FSE_NOT_READY) {
        uhf_diag_log(app, "Hard reset: SD unmount failed %d", (int)unmount_error);
        furi_record_close(RECORD_STORAGE);
        return false;
    }

    /* Put both UART lines low before the supply falls, keep them low while the
       reader is unpowered, and hold them low throughout its next power-up. */
    furi_hal_gpio_write(&gpio_usart_tx, false);
    furi_hal_gpio_write(&gpio_usart_rx, false);
    furi_hal_gpio_init_simple(&gpio_usart_tx, GpioModeOutputPushPull);
    furi_hal_gpio_init_simple(&gpio_usart_rx, GpioModeOutputPushPull);

    uhf_diag_log(app, "Hard reset: UART low, external 3.3V off");
    furi_hal_power_disable_external_3_3v();
    furi_delay_ms(UHF_POWER_OFF_MS);

    furi_hal_power_enable_external_3_3v();

    FS_Error mount_error = FSE_NOT_READY;
    uint32_t power_boot_elapsed_ms = 0U;
    for(uint8_t attempt = 0U; attempt < 8U && mount_error != FSE_OK; attempt++) {
        furi_delay_ms(100U);
        power_boot_elapsed_ms += 100U;
        mount_error = storage_sd_mount(storage);
    }

    if(UHF_POWER_BOOT_MS > power_boot_elapsed_ms) {
        furi_delay_ms(UHF_POWER_BOOT_MS - power_boot_elapsed_ms);
    }

    furi_hal_gpio_init_simple(&gpio_usart_tx, GpioModeAnalog);
    furi_hal_gpio_init_simple(&gpio_usart_rx, GpioModeAnalog);
    furi_delay_ms(UHF_POWER_READY_MS);
    furi_record_close(RECORD_STORAGE);

    if(mount_error != FSE_OK) {
        uhf_diag_log(app, "Hard reset: SD mount failed %d", (int)mount_error);
        return false;
    }

    app->baud_rate = UHF_BAUD_RATE;
    if(!uhf_open_bridge_uart(app)) {
        uhf_diag_log(app, "Hard reset: UART reopen failed");
        return false;
    }

    app->hardware_ready = true;
    uhf_hardware_reset_reader(app);
    app->frame_buffer_len = 0U;
    if(app->rx_stream) furi_stream_buffer_reset(app->rx_stream);
    uhf_clear_version(app);
    uhf_diag_log(app, "Hard reset complete");
    return true;
}

static void uhf_service_inventory(UhfApp* app) {
    if(!app || !app->inventory_running) return;

    const uint32_t now = furi_get_tick();
    if(app->temperature_query_pending &&
       (now - app->last_temperature_query_tick) >= UHF_READER_QUERY_TIMEOUT_MS) {
        app->temperature_query_pending = false;
        uhf_diag_log(app, "Temperature query timeout");
    }
    if(!app->temperature_query_pending &&
       (now - app->last_temperature_query_tick) >= UHF_TEMP_REFRESH_MS) {
        (void)uhf_query_reader_temperature(app, false);
        return;
    }

    const bool session_renew_due =
        (now - app->last_inv_session_tick) >= UHF_INV_SESSION_RENEW_MS;
    if(session_renew_due) {
        static const uint8_t stop_frame[] = {0xA0, 0x03, 0x00, 0x8C, 0xD1};
        static const uint8_t start_frame[] = {0xA0, 0x04, 0x00, 0x89, 0x01, 0xD2};

        (void)uhf_send_raw_frame(app, stop_frame, sizeof(stop_frame));
        furi_delay_ms(UHF_INV_RENEW_SETTLE_MS);
        uhf_process_rx(app);

        const uint32_t restarted_at = furi_get_tick();
        if(uhf_send_raw_frame(app, start_frame, sizeof(start_frame))) {
            app->last_inv_refresh_tick = restarted_at;
            app->last_inv_session_tick = restarted_at;
            uhf_set_status(app, "Inventory running");
            uhf_diag_log(app, "Inventory session renewed");
        } else {
            app->last_inv_session_tick = restarted_at;
            uhf_set_status(app, "Inventory restart failed");
        }
        return;
    }

    const bool heartbeat_due =
        (now - app->last_inv_refresh_tick) >= UHF_INV_HEARTBEAT_MS;
    if(!heartbeat_due) return;

    /* The reader's completion response is not a reliable pacing signal and
       immediately chaining on it can overrun the reader. Match the proven
       Cardputer cadence: start one repeat every 250 ms without inserting a
       stop command or clearing buffered reports between rounds. */
    static const uint8_t start_frame[] = {0xA0, 0x04, 0x00, 0x89, 0x01, 0xD2};

    if(uhf_send_raw_frame(app, start_frame, sizeof(start_frame))) {
        app->last_inv_refresh_tick = now;
        uhf_set_status(app, "Inventory running");
    } else {
        app->last_inv_refresh_tick = now;
        uhf_set_status(app, "Inventory restart failed");
    }
}

static void uhf_request_version(UhfApp* app) {
    if(!uhf_ensure_hardware(app)) return;
    app->frame_buffer_len = 0;
    app->rx_bytes = 0;
    app->rx_frames = 0;
    app->rx_errors = 0;
    app->last_rx_hex[0] = '\0';
    uhf_clear_version(app);
    if(app->rx_stream) {
        (void)furi_stream_buffer_reset(app->rx_stream);
    }

    static const uint8_t version_frame[] = {0xA0, 0x03, 0x00, 0x72, 0xEB};
    bool sent = false;
    for(size_t attempt = 0; attempt < 2; attempt++) {
        if(uhf_send_raw_frame(app, version_frame, sizeof(version_frame))) {
            sent = true;
        }
        uhf_process_rx(app);
        furi_delay_ms(8);
    }

    if(sent) {
        uhf_set_status(app, "Version checking...");
        uhf_diag_log(app, "Version req TX:%d RX:%d", app->tx_ext_pin, app->rx_ext_pin);
    } else {
        uhf_set_status(app, "Version tx failed");
        uhf_diag_log(app, "Version tx failed");
    }
}

static bool uhf_add_inventory_tag(
    UhfApp* app,
    const uint8_t* epc,
    size_t epc_len,
    uint8_t antenna,
    uint32_t rssi,
    uint32_t frequency,
    uint32_t hit_count) {
    if(!uhf_is_valid_epc(epc, epc_len)) return false;
    if(hit_count == 0U) hit_count = 1U;

    char epc_hex[UHF_EPC_HEX_MAX + 1];
    if(!uhf_bytes_to_hex(epc, epc_len, epc_hex, sizeof(epc_hex))) return false;

    bool is_new_tag = false;
    if(!uhf_data_lock(app, 10)) return false;

    UhfTagEntry* tag = uhf_find_or_add_tag(app, epc_hex, &is_new_tag);
    if(!tag) {
        uhf_data_unlock(app);
        uhf_set_status(app, "Tag cache full");
        return false;
    }

    const uint32_t updated_count = (uint32_t)tag->read_count + hit_count;
    tag->read_count = updated_count > UINT16_MAX ? UINT16_MAX : (uint16_t)updated_count;
    app->rate_window_reads += hit_count;
    tag->last_seen = furi_get_tick();
    tag->antenna = antenna;
    tag->rssi = rssi;
    tag->frequency = frequency;
    uhf_data_unlock(app);

    uhf_notify_tag_found(app);

    if(is_new_tag) {
        const size_t total = uhf_count_tags(app);
        if(!app->list_selection_manual) {
            if(total > UHF_LIST_VISIBLE_ROWS) {
                app->list_top_index = total - UHF_LIST_VISIBLE_ROWS;
            } else {
                app->list_top_index = 0;
            }
            app->list_selected_index = total ? (total - 1U) : 0;
        }
        uhf_set_status(app, "Tag Found: %lu", (unsigned long)total);
    }

    return true;
}

static bool uhf_parse_pc_epc_at(UhfApp* app, const uint8_t* data, size_t data_len, size_t pc_offset, uint8_t antenna) {
    if(data_len < pc_offset + 4U) return false;

    const uint16_t pc = (uint16_t)((data[pc_offset] << 8) | data[pc_offset + 1U]);
    const size_t epc_words = (pc >> 11) & 0x1F;
    const size_t epc_len = epc_words * 2U;
    const size_t epc_offset = pc_offset + 2U;
    const size_t meta_offset = epc_offset + epc_len;

    if(epc_len == 0 || epc_len > (UHF_EPC_HEX_MAX / 2U) || data_len < meta_offset) return false;

    uint32_t rssi = 0;
    uint32_t frequency = 0;
    if(data_len >= meta_offset + 7U) {
        rssi = uhf_read_be(&data[meta_offset], 4);
        frequency = uhf_read_be(&data[meta_offset + 4U], 3);
    }

    return uhf_add_inventory_tag(app, &data[epc_offset], epc_len, antenna, rssi, frequency, 1U);
}

static bool uhf_parse_inventory_buffer_frame(UhfApp* app, const uint8_t* data, size_t data_len) {
    if(data_len < 11U) return false;

    const size_t inv_data_len = data[0];
    const size_t required_len = 1U + inv_data_len + 4U + 3U + 1U + 1U;
    if(inv_data_len < 4U || data_len < required_len) return false;

    const uint8_t* inv_data = &data[1];
    const size_t epc_len = inv_data_len - 4U;
    const size_t offset = 1U + inv_data_len;
    const uint8_t antenna = data[offset + 7U];
    uint32_t hit_count = data[offset + 8U];
    if(hit_count == 0U) hit_count = 1U;
    const uint32_t rssi = uhf_read_be(&data[offset], 4);
    const uint32_t frequency = uhf_read_be(&data[offset + 4U], 3);

    return uhf_add_inventory_tag(
        app, &inv_data[2], epc_len, antenna, rssi, frequency, hit_count);
}

static bool uhf_parse_inventory_frame(UhfApp* app, const uint8_t* data, size_t data_len, uint8_t cmd) {
    if(cmd == UHF_CMD_INV_ALT && uhf_parse_inventory_buffer_frame(app, data, data_len)) {
        return true;
    }
    if(uhf_parse_pc_epc_at(app, data, data_len, 1U, data_len ? data[0] : 0U)) return true;
    if(cmd != UHF_CMD_INV_ALT && uhf_parse_inventory_buffer_frame(app, data, data_len)) {
        return true;
    }

    for(size_t offset = 0; offset < 3U && offset < data_len; offset++) {
        if(uhf_parse_pc_epc_at(app, data, data_len, offset, 0)) return true;
    }

    return false;
}

static void uhf_handle_frame(UhfApp* app, const uint8_t* frame, size_t frame_size) {
    if(frame_size < 5U || frame[0] != UHF_FRAME_START) return;

    uhf_store_last_rx_hex(app, frame, frame_size);

    uint8_t checksum_acc = 0;
    for(size_t i = 0; i < frame_size; i++) {
        checksum_acc = (uint8_t)(checksum_acc + frame[i]);
    }
    if(checksum_acc != 0U) {
        app->rx_errors++;
    }

    app->rx_frames++;

    const uint8_t cmd = frame[3];
    const size_t data_len = (frame[1] >= 3U) ? (size_t)(frame[1] - 3U) : 0U;
    const uint8_t* data = &frame[4];

    uhf_diag_log(
        app,
        "RX cmd=%02X len=%lu cs=%s",
        cmd,
        (unsigned long)data_len,
        (checksum_acc == 0U) ? "ok" : "bad");

    if(cmd == UHF_CMD_READ_TAG || cmd == UHF_CMD_WRITE_TAG ||
       cmd == UHF_CMD_SET_EPC_MATCH) {
        FURI_LOG_I(
            TAG,
            "Tag RX cmd=%02X len=%lu cs=%s raw=%s",
            cmd,
            (unsigned long)data_len,
            checksum_acc == 0U ? "ok" : "bad",
            app->last_rx_hex);
    }

    if(cmd == UHF_CMD_READ_TAG || cmd == UHF_CMD_WRITE_TAG ||
       cmd == UHF_CMD_SET_EPC_MATCH) {
        const size_t copied = data_len > sizeof(app->tag_reply) ? sizeof(app->tag_reply) : data_len;
        if(copied) memcpy(app->tag_reply, data, copied);
        app->tag_reply_len = copied;
        app->tag_reply_cmd = cmd;
        app->tag_reply_checksum_ok = checksum_acc == 0U;
        app->tag_reply_ready = true;
        return;
    }

    if(cmd == UHF_CMD_GET_VERSION && data_len >= 3U) {
        if(uhf_data_lock(app, 10)) {
            snprintf(app->version, sizeof(app->version), "%u.%u.%u", data[0], data[1], data[2]);
            uhf_data_unlock(app);
        }
        uhf_set_status(app, "Version %s", app->version);
        uhf_diag_log(app, "Version=%s", app->version);
    } else if(cmd == UHF_CMD_GET_TEMP) {
        app->temperature_query_pending = false;
        FURI_LOG_I(
            TAG,
            "Temperature response: len=%lu sign=%u value=%u checksum=%s",
            (unsigned long)data_len,
            data_len >= 1U ? data[0] : 0U,
            data_len >= 2U ? data[1] : 0U,
            checksum_acc == 0U ? "ok" : "bad");
        if(checksum_acc == 0U && data_len >= 2U && data[0] <= 1U) {
            int16_t raw_temperature = (int16_t)data[1];
            if(data[0] == 0U) raw_temperature = -raw_temperature;
            const int16_t display_temperature =
                raw_temperature + UHF_TEMP_DISPLAY_OFFSET_C;
            if(uhf_data_lock(app, 10)) {
                app->reader_temperature_c = display_temperature;
                app->temperature_valid = true;
                uhf_data_unlock(app);
            }
            uhf_diag_log(
                app,
                "Temperature raw=%dC display=%dC",
                (int)raw_temperature,
                (int)display_temperature);
            FURI_LOG_I(
                TAG,
                "Reader temperature: raw=%d C display=%d C",
                (int)raw_temperature,
                (int)display_temperature);
        } else {
            uhf_diag_log(app, "Temperature query failed");
            FURI_LOG_W(TAG, "Reader temperature query failed");
        }
    } else if(cmd == UHF_CMD_GET_POWER) {
        app->power_query_pending = false;
        if(checksum_acc == 0U && data_len >= 1U && data[0] <= 33U) {
            if(uhf_data_lock(app, 10)) {
                /* This expansion uses antenna 1; multi-antenna readers return
                   additional power bytes after the first one. */
                app->reader_power_dbm = data[0];
                app->power_valid = true;
                uhf_data_unlock(app);
            }
            uhf_diag_log(app, "Power=%udBm", data[0]);
            FURI_LOG_I(TAG, "Reader output power: %u dBm", data[0]);
        } else {
            uhf_diag_log(app, "Power query failed");
            FURI_LOG_W(TAG, "Reader output power query failed");
        }
    } else if(cmd == UHF_CMD_START_INV || cmd == UHF_CMD_INV_ALT || app->inventory_running) {
        const bool parsed_tag = uhf_parse_inventory_frame(app, data, data_len, cmd);
        if(!parsed_tag &&
            checksum_acc == 0U && (cmd == UHF_CMD_START_INV || cmd == UHF_CMD_INV_ALT) &&
            data_len <= 7U) {
            /* A short 0x89/0x8A reply is completion/error status, not tag data.
               The fixed inventory heartbeat starts the next round. */
            uhf_diag_log(app, "Inventory ended cmd=%02X len=%lu", cmd, (unsigned long)data_len);
        }
    } else if(cmd == UHF_CMD_STOP_INV) {
        if(!app->inventory_running) {
            uhf_set_status(app, "Inventory stopped");
        }
    }
}

static void uhf_process_rx(UhfApp* app) {
    uint8_t chunk[64];
    size_t got = 0;
    size_t chunk_budget = UHF_RX_CHUNKS_PER_PASS;
    size_t frame_budget = UHF_RX_FRAMES_PER_PASS;

    while(chunk_budget && frame_budget &&
          (got = furi_stream_buffer_receive(app->rx_stream, chunk, sizeof(chunk), 0)) > 0U) {
        chunk_budget--;
        app->rx_bytes += got;
        if(app->frame_buffer_len + got > sizeof(app->frame_buffer)) {
            app->rx_errors++;
            app->frame_buffer_len = 0;
        }

        memcpy(&app->frame_buffer[app->frame_buffer_len], chunk, got);
        app->frame_buffer_len += got;

        size_t index = 0;
        while(index < app->frame_buffer_len) {
            while(index < app->frame_buffer_len && app->frame_buffer[index] != UHF_FRAME_START) {
                index++;
            }
            if((app->frame_buffer_len - index) < 2U) break;

            const size_t frame_size = (size_t)app->frame_buffer[index + 1U] + 2U;
            if(frame_size < 5U) {
                app->rx_errors++;
                index++;
                continue;
            }
            if((app->frame_buffer_len - index) < frame_size) break;

            uhf_handle_frame(app, &app->frame_buffer[index], frame_size);
            index += frame_size;

            frame_budget--;
            if(frame_budget == 0U) {
                break;
            }
        }

        if(index > 0U) {
            const size_t remain = app->frame_buffer_len - index;
            if(remain) {
                memmove(app->frame_buffer, &app->frame_buffer[index], remain);
            }
            app->frame_buffer_len = remain;
        }

        if(frame_budget == 0U) {
            break;
        }
    }

}

static bool uhf_wait_for_version(UhfApp* app, uint32_t timeout_ms) {
    const uint32_t started = furi_get_tick();
    while((furi_get_tick() - started) < timeout_ms) {
        uhf_process_rx(app);
        if(uhf_has_version(app)) {
            return true;
        }
        furi_delay_ms(12U);
    }
    return false;
}

static bool uhf_probe_current_serial(UhfApp* app, uint32_t baud) {
    if(!app->serial) return false;

    uhf_apply_baud(app, baud);
    uhf_clear_version(app);
    if(!uhf_has_version(app)) {
        uhf_request_version(app);
    }
    return uhf_wait_for_version(app, UHF_PROBE_TIMEOUT_MS);
}

static bool uhf_save_diag_log(UhfApp* app) {
    Storage* storage = furi_record_open(RECORD_STORAGE);
    if(!storage) {
        uhf_set_status(app, "Storage unavailable");
        return false;
    }

    if(!storage_dir_exists(storage, UHF_APP_DATA_DIR)) {
        const FS_Error mkdir_result = storage_common_mkdir(storage, UHF_APP_DATA_DIR);
        if(mkdir_result != FSE_OK && mkdir_result != FSE_EXIST) {
            furi_record_close(RECORD_STORAGE);
            uhf_set_status(app, "Create dir failed");
            return false;
        }
    }

    char path[128];
    const uint32_t now = furi_get_tick();
    snprintf(path, sizeof(path), UHF_APP_DATA_DIR "/diag_%lu.log", (unsigned long)now);

    File* file = storage_file_alloc(storage);
    if(!file) {
        furi_record_close(RECORD_STORAGE);
        uhf_set_status(app, "File alloc failed");
        return false;
    }

    bool ok = false;
    do {
        if(!storage_file_open(file, path, FSAM_WRITE, FSOM_CREATE_ALWAYS)) {
            uhf_set_status(app, "Open log failed");
            break;
        }

        char header[128];
        const int header_len = snprintf(
            header,
            sizeof(header),
            "diag tick=%lu tx=%d rx=%d baud=%lu\\n",
            (unsigned long)now,
            app->tx_ext_pin,
            app->rx_ext_pin,
            (unsigned long)app->baud_rate);
        if(header_len > 0) {
            (void)storage_file_write(file, header, (size_t)header_len);
        }

        const size_t count = app->diag_count;
        const size_t start = (app->diag_head + UHF_DIAG_LOG_LINES - count) % UHF_DIAG_LOG_LINES;
        for(size_t i = 0; i < count; i++) {
            const size_t idx = (start + i) % UHF_DIAG_LOG_LINES;
            const char* line = app->diag_log[idx];
            if(!line[0]) continue;
            const size_t len = strlen(line);
            if(len) {
                (void)storage_file_write(file, line, len);
                (void)storage_file_write(file, "\\n", 1);
            }

            // Yield periodically to keep UI/task scheduler responsive on long writes.
            if((i & 0x07U) == 0x07U) {
                furi_delay_ms(1);
            }
        }

        storage_file_sync(file);
        uhf_set_status(app, "Diag saved: %s", path);
        ok = true;
    } while(false);

    storage_file_close(file);
    storage_file_free(file);
    furi_record_close(RECORD_STORAGE);
    return ok;
}

static void uhf_clear_tags(UhfApp* app) {
    if(uhf_data_lock(app, 10)) {
        memset(app->tags, 0, sizeof(app->tags));
        app->tag_count = 0;
        app->list_top_index = 0;
        app->list_selected_index = 0;
        app->list_selection_manual = false;
        uhf_data_unlock(app);
    }
    uhf_set_status(app, "Records cleared");
}

static void uhf_update_inventory_rate(UhfApp* app) {
    if(!app) return;

    const uint32_t now = furi_get_tick();
    if(app->rate_window_started == 0U) {
        app->rate_window_started = now;
        return;
    }

    const uint32_t elapsed = now - app->rate_window_started;
    if(elapsed < 1000U) return;

    if(uhf_data_lock(app, 10)) {
        app->tags_per_second = app->inventory_running ?
                                   (uint32_t)(((uint64_t)app->rate_window_reads * 1000U) / elapsed) :
                                   0U;
        app->rate_window_reads = 0U;
        app->rate_window_started = now;
        uhf_data_unlock(app);
    }
}

static void uhf_update_radar_animation(UhfApp* app) {
    if(!app) return;

    const uint32_t now = furi_get_tick();
    if(!app->inventory_running) {
        /* Prevent a paused radar from catching up when inventory resumes. */
        app->radar_step_tick = now;
        return;
    }

    if(app->radar_step_tick == 0U) {
        app->radar_step_tick = now;
        return;
    }

    const uint32_t elapsed = now - app->radar_step_tick;
    if(elapsed < UHF_RADAR_STEP_MS) return;

    const uint32_t steps = elapsed / UHF_RADAR_STEP_MS;
    app->radar_sweep_phase =
        (uint8_t)((app->radar_sweep_phase + steps) % UHF_RADAR_PHASE_COUNT);
    if(app->page == UhfPageRadar && app->radar_trail_depth < 8U) {
        const uint32_t depth = app->radar_trail_depth + steps;
        app->radar_trail_depth = (uint8_t)(depth > 8U ? 8U : depth);
    }
    app->radar_step_tick += steps * UHF_RADAR_STEP_MS;
}

static size_t uhf_collect_tag_previews(
    UhfApp* app,
    size_t start,
    UhfTagPreview* out,
    size_t max_items,
    size_t* total) {
    if(!app || !out || !max_items || !total) return 0;
    if(!uhf_data_lock(app, 20)) return 0;

    size_t copied = 0;
    size_t index = 0;
    size_t used_total = 0;

    for(size_t i = 0; i < UHF_MAX_TAGS; i++) {
        if(!app->tags[i].used) continue;

        if(index >= start && copied < max_items) {
            strncpy(out[copied].epc, app->tags[i].epc, sizeof(out[copied].epc) - 1);
            out[copied].epc[sizeof(out[copied].epc) - 1] = '\0';
            out[copied].count = app->tags[i].read_count;
            copied++;
        }

        index++;
        used_total++;
    }

    *total = used_total;
    uhf_data_unlock(app);
    return copied;
}

static void uhf_draw_centered_text(Canvas* canvas, int y, const char* text) {
    if(!canvas || !text) return;

    const int width = canvas_string_width(canvas, text);
    int x = (128 - width) / 2;
    if(x < 0) x = 0;
    canvas_draw_str(canvas, x, y, text);
}

static void uhf_draw_radar_ring(
    Canvas* canvas,
    int32_t center_x,
    int32_t center_y,
    const int8_t* ring_x,
    const int8_t* ring_y,
    int32_t scale) {
    for(uint8_t i = 0; i < 24U; i++) {
        const uint8_t next = (uint8_t)((i + 1U) % 24U);
        canvas_draw_line(
            canvas,
            center_x + ((int32_t)ring_x[i] * scale) / 27,
            center_y + ((int32_t)ring_y[i] * scale) / 27,
            center_x + ((int32_t)ring_x[next] * scale) / 27,
            center_y + ((int32_t)ring_y[next] * scale) / 27);
    }
}

static int32_t uhf_radar_sin(uint8_t phase) {
    static const uint8_t quarter_wave[25] = {
        0, 8, 17, 25, 33, 41, 49, 56, 63, 71, 77, 84, 90,
        95, 101, 106, 110, 114, 117, 120, 123, 125, 126, 127, 127,
    };

    phase %= UHF_RADAR_PHASE_COUNT;
    const uint8_t quadrant = phase / 24U;
    const uint8_t offset = phase % 24U;

    if(quadrant == 0U) return quarter_wave[offset];
    if(quadrant == 1U) return quarter_wave[24U - offset];
    if(quadrant == 2U) return -(int32_t)quarter_wave[offset];
    return -(int32_t)quarter_wave[24U - offset];
}

static void uhf_radar_vector(uint8_t phase, int32_t radius, int32_t* x, int32_t* y) {
    *x = (uhf_radar_sin(phase) * radius * 29) / (127 * 27);
    *y = -(uhf_radar_sin((uint8_t)(phase + 24U)) * radius) / 127;
}

static void uhf_draw_radar_page(Canvas* canvas, UhfApp* app) {
    static const int8_t sweep_x[24] = {
        0, 8, 15, 21, 25, 28, 29, 28, 25, 21, 15, 8,
        0, -8, -15, -21, -25, -28, -29, -28, -25, -21, -15, -8,
    };
    static const int8_t sweep_y[24] = {
        -27, -26, -23, -19, -14, -7, 0, 7, 14, 19, 23, 26,
        27, 26, 23, 19, 14, 7, 0, -7, -14, -19, -23, -26,
    };

    const int32_t center_x = 31;
    const int32_t center_y = 36;
    uint8_t target_x[UHF_MAX_TAGS];
    uint8_t target_y[UHF_MAX_TAGS];
    size_t target_count = 0;
    uint32_t rate = 0;
    size_t unique = 0;
    int16_t temperature = 0;
    uint8_t power_dbm = 0;
    bool temperature_valid = false;
    bool power_valid = false;
    uint8_t sweep_phase = 0;
    uint8_t trail_depth = 0;

    if(uhf_data_lock(app, 10)) {
        rate = app->tags_per_second;
        unique = app->tag_count;
        temperature = app->reader_temperature_c;
        power_dbm = app->reader_power_dbm;
        temperature_valid = app->temperature_valid;
        power_valid = app->power_valid;
        sweep_phase = app->radar_sweep_phase;
        trail_depth = app->radar_trail_depth;

        for(size_t i = 0; i < UHF_MAX_TAGS && target_count < UHF_MAX_TAGS; i++) {
            if(!app->tags[i].used) continue;

            /* Stable FNV-1a placement keeps each EPC at the same radar
               position while avoiding any artificial distance claim. */
            uint32_t hash = 2166136261U;
            for(const char* p = app->tags[i].epc; *p; p++) {
                hash ^= (uint8_t)*p;
                hash *= 16777619U;
            }

            /* Place targets across the upper semicircle (left horizon through
               top to right horizon), where they remain easiest to see. */
            const uint8_t upper_slot = (uint8_t)(hash % 13U);
            const uint8_t direction = (uint8_t)((18U + upper_slot) % 24U);
            const int32_t distance = 5 + (int32_t)((hash >> 8U) % 20U);
            const int32_t x = center_x + ((int32_t)sweep_x[direction] * distance) / 27;
            const int32_t y = center_y + ((int32_t)sweep_y[direction] * distance) / 27;
            target_x[target_count] = (uint8_t)x;
            target_y[target_count] = (uint8_t)y;
            target_count++;
        }
        uhf_data_unlock(app);
    }

    canvas_set_font(canvas, FontPrimary);
    const char* radar_title = "UHF Radar";
    const int32_t title_width = canvas_string_width(canvas, radar_title);
    canvas_draw_str(canvas, (65 - title_width) / 2, 8, radar_title);

    uhf_draw_radar_ring(canvas, center_x, center_y, sweep_x, sweep_y, 27);
    uhf_draw_radar_ring(canvas, center_x, center_y, sweep_x, sweep_y, 18);
    uhf_draw_radar_ring(canvas, center_x, center_y, sweep_x, sweep_y, 9);
    canvas_draw_dot(canvas, center_x, center_y);
    for(int32_t offset = -25; offset <= 25; offset += 5) {
        canvas_draw_dot(canvas, center_x + offset, center_y);
    }
    for(int32_t offset = -25; offset <= 25; offset += 5) {
        canvas_draw_dot(canvas, center_x, center_y + offset);
    }

    /* All trail segments keep their full length. Older segments use fewer
       pixels, creating a stable pseudo-gray fade on the 1-bit display. */
    for(uint8_t age = trail_depth; age > 0U; age--) {
        const uint8_t trail_phase =
            (uint8_t)((sweep_phase + UHF_RADAR_PHASE_COUNT - age) %
                      UHF_RADAR_PHASE_COUNT);
        for(int32_t step = 4; step <= 27; step++) {
            if(((step + age) % (age + 1U)) != 0U) continue;
            int32_t trail_x = 0;
            int32_t trail_y = 0;
            uhf_radar_vector(trail_phase, step, &trail_x, &trail_y);
            canvas_draw_dot(canvas, center_x + trail_x, center_y + trail_y);
        }
    }

    int32_t sweep_dx = 0;
    int32_t sweep_dy = 0;
    uhf_radar_vector(sweep_phase, 27, &sweep_dx, &sweep_dy);
    canvas_draw_line(canvas, center_x, center_y, center_x + sweep_dx, center_y + sweep_dy);

    /* Draw a parallel one-pixel offset to make the leading sweep two pixels
       thick at every angle. */
    const int32_t abs_dx = sweep_dx < 0 ? -sweep_dx : sweep_dx;
    const int32_t abs_dy = sweep_dy < 0 ? -sweep_dy : sweep_dy;
    const int32_t offset_x =
        (abs_dy > abs_dx) ? ((sweep_dy > 0) ? -1 : 1) : 0;
    const int32_t offset_y =
        (abs_dy > abs_dx) ? 0 : ((sweep_dx >= 0) ? 1 : -1);
    canvas_draw_line(
        canvas,
        center_x + offset_x,
        center_y + offset_y,
        center_x + sweep_dx + offset_x,
        center_y + sweep_dy + offset_y);

    /* Draw targets last so they remain solid above the sweep and trail. */
    for(size_t i = 0; i < target_count; i++) {
        canvas_draw_box(canvas, (int32_t)target_x[i] - 1, (int32_t)target_y[i] - 1, 3, 3);
    }

    canvas_draw_line(canvas, 65, 0, 65, 63);

    canvas_set_font(canvas, FontSecondary);
    char value[24];

    canvas_draw_str(canvas, 70, 10, "RATE");
    if(rate > 9999U) {
        snprintf(value, sizeof(value), "9999+");
    } else {
        snprintf(value, sizeof(value), "%lu/s", (unsigned long)rate);
    }
    uhf_draw_right_text(canvas, 10, value);

    canvas_draw_str(canvas, 70, 26, "TAGS");
    snprintf(value, sizeof(value), "%lu", (unsigned long)unique);
    uhf_draw_right_text(canvas, 26, value);

    canvas_draw_str(canvas, 70, 42, "TEMP");
    if(temperature_valid) {
        snprintf(value, sizeof(value), "%d", (int)temperature);
    } else {
        snprintf(value, sizeof(value), "--");
    }
    uhf_draw_right_temperature(canvas, 42, value);

    canvas_draw_str(canvas, 70, 58, "PWR");
    if(power_valid) {
        snprintf(value, sizeof(value), "%udBm", power_dbm);
    } else {
        snprintf(value, sizeof(value), "--");
    }
    uhf_draw_right_text(canvas, 58, value);
}

