static void uhf_format_hex_bytes_spaced(
    const char* hex,
    size_t hex_chars,
    char* out,
    size_t out_size) {
    if(!hex || !out || out_size == 0U) return;

    size_t written = 0U;
    for(size_t i = 0U; i < hex_chars && hex[i]; i++) {
        if(i > 0U && (i % 2U) == 0U) {
            if(written + 1U >= out_size) break;
            out[written++] = ' ';
        }
        if(written + 1U >= out_size) break;
        out[written++] = hex[i];
    }
    out[written] = '\0';
}

