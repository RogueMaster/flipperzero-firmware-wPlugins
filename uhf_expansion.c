static void uhf_diag_log(UhfApp* app, const char* fmt, ...) {
    if(!app) return;

    char line[UHF_DIAG_LOG_LEN];
    va_list args;
    va_start(args, fmt);
    vsnprintf(line, sizeof(line), fmt, args);
    va_end(args);

    const uint8_t idx = app->diag_head;
    strncpy(app->diag_log[idx], line, UHF_DIAG_LOG_LEN - 1U);
    app->diag_log[idx][UHF_DIAG_LOG_LEN - 1U] = '\0';

    app->diag_head = (uint8_t)((idx + 1U) % UHF_DIAG_LOG_LINES);
    if(app->diag_count < UHF_DIAG_LOG_LINES) {
        app->diag_count++;
    }
}

static void uhf_force_direct_a6_a4(UhfApp* app) {
    if(!app) return;

    // Bridge wiring mode: use hardware UART lines on ext 13/14 for stable real-time RX.
    if(app->serial) {
        uhf_close_serial(app);
    }

    if(!uhf_open_bridge_uart(app)) {
        app->tx_ext_pin = -1;
        app->rx_ext_pin = -1;
        return;
    }

    app->baud_rate = UHF_BAUD_RATE;
    furi_hal_serial_set_br(app->serial, app->baud_rate);

    app->frame_buffer_len = 0;
    app->last_rx_hex[0] = '\0';
    if(app->rx_stream) {
        (void)furi_stream_buffer_reset(app->rx_stream);
    }

    uhf_diag_log(app, "Bridge UART TX:%d RX:%d", app->tx_ext_pin, app->rx_ext_pin);
}

static bool uhf_data_lock(UhfApp* app, uint32_t timeout) {
    if(!app->data_mutex) return false;
    return furi_mutex_acquire(app->data_mutex, timeout) == FuriStatusOk;
}

static void uhf_data_unlock(UhfApp* app) {
    if(app->data_mutex) {
        furi_mutex_release(app->data_mutex);
    }
}

static void uhf_set_status(UhfApp* app, const char* fmt, ...) {
    char buffer[sizeof(app->status)];

    va_list args;
    va_start(args, fmt);
    vsnprintf(buffer, sizeof(buffer), fmt, args);
    va_end(args);

    if(uhf_data_lock(app, 10)) {
        strncpy(app->status, buffer, sizeof(app->status) - 1);
        app->status[sizeof(app->status) - 1] = '\0';
        uhf_data_unlock(app);
    } else {
        strncpy(app->status, buffer, sizeof(app->status) - 1);
        app->status[sizeof(app->status) - 1] = '\0';
    }
}

#define UHF_TAG_BEEP_COOLDOWN_MS 20U

static void uhf_notify_tag_found(UhfApp* app) {
    if(!app || !app->notifications) return;
    if(!app->tag_beep_enabled) return;

    /* Match the main RX polling cadence for prompt feedback without flooding
       the asynchronous notification queue with duplicate sounds. */
    const uint32_t now = furi_get_tick();
    if((now - app->last_tag_beep_tick) < UHF_TAG_BEEP_COOLDOWN_MS) return;

    app->last_tag_beep_tick = now;
    notification_message(app->notifications, &uhf_sequence_tag_found);
}

static void uhf_notify_write_result(UhfApp* app, bool success) {
    if(!app || !app->notifications) return;
    notification_message(app->notifications, success ? &sequence_success : &sequence_error);
}

static void uhf_filename_input_done(void* context) {
    UhfFilenameInputCtx* ctx = context;
    if(!ctx) return;

    ctx->submitted = true;
    if(ctx->dispatcher) {
        view_dispatcher_stop(ctx->dispatcher);
    }
}

static bool uhf_filename_input_back(void* context) {
    UhfFilenameInputCtx* ctx = context;
    if(!ctx) return true;

    if(ctx->dispatcher) {
        view_dispatcher_stop(ctx->dispatcher);
    }
    return true;
}

static void uhf_sanitize_filename(const char* input, char* out, size_t out_size) {
    if(!out || out_size == 0) return;

    size_t j = 0;
    if(input) {
        for(size_t i = 0; input[i] && j + 1 < out_size; i++) {
            const unsigned char c = (unsigned char)input[i];
            if(isalnum(c) || c == '_' || c == '-') {
                out[j++] = (char)c;
            }
        }
    }

    if(j == 0) {
        strncpy(out, "tags", out_size - 1);
        out[out_size - 1] = '\0';
    } else {
        out[j] = '\0';
    }
}

static bool uhf_prompt_csv_filename(UhfApp* app, char* out, size_t out_size) {
    if(!app || !app->gui || !app->view_port || !out || out_size < 2) return false;

    strncpy(out, "tags", out_size - 1);
    out[out_size - 1] = '\0';

    TextInput* text_input = text_input_alloc();
    ViewDispatcher* dispatcher = view_dispatcher_alloc();
    if(!text_input || !dispatcher) {
        if(text_input) text_input_free(text_input);
        if(dispatcher) view_dispatcher_free(dispatcher);
        return false;
    }

    UhfFilenameInputCtx ctx = {
        .dispatcher = dispatcher,
        .submitted = false,
    };

    text_input_set_header_text(text_input, "CSV file name");
    text_input_set_minimum_length(text_input, 1);
    text_input_set_result_callback(text_input, uhf_filename_input_done, &ctx, out, out_size, false);

    view_dispatcher_set_event_callback_context(dispatcher, &ctx);
    view_dispatcher_set_navigation_event_callback(dispatcher, uhf_filename_input_back);
    view_dispatcher_add_view(dispatcher, 0, text_input_get_view(text_input));

    gui_remove_view_port(app->gui, app->view_port);
    view_dispatcher_attach_to_gui(dispatcher, app->gui, ViewDispatcherTypeFullscreen);
    view_dispatcher_switch_to_view(dispatcher, 0);
    view_dispatcher_run(dispatcher);

    view_dispatcher_remove_view(dispatcher, 0);
    view_dispatcher_free(dispatcher);
    text_input_free(text_input);

    gui_add_view_port(app->gui, app->view_port, GuiLayerFullscreen);

    if(!ctx.submitted) return false;

    char safe_name[32];
    uhf_sanitize_filename(out, safe_name, sizeof(safe_name));
    strncpy(out, safe_name, out_size - 1);
    out[out_size - 1] = '\0';
    return out[0] != '\0';
}

static bool uhf_normalize_hex(char* value, size_t max_hex_len) {
    if(!value) return false;

    size_t write = 0U;
    for(size_t read = 0U; value[read]; read++) {
        const unsigned char c = (unsigned char)value[read];
        if(c == ' ' || c == ':' || c == '-') continue;
        if(!isxdigit(c) || write >= max_hex_len) return false;
        value[write++] = (char)toupper(c);
    }
    value[write] = '\0';
    return write >= 4U && (write % 4U) == 0U;
}

static bool uhf_prompt_memory_hex(
    UhfApp* app,
    const char* header,
    char* out,
    size_t out_size,
    size_t max_hex_len) {
    if(!app || !app->gui || !app->view_port || !out || out_size < 5U) return false;

    if(!out[0]) strncpy(out, "0000", out_size - 1U);
    out[out_size - 1U] = '\0';

    TextInput* text_input = text_input_alloc();
    ViewDispatcher* dispatcher = view_dispatcher_alloc();
    if(!text_input || !dispatcher) {
        if(text_input) text_input_free(text_input);
        if(dispatcher) view_dispatcher_free(dispatcher);
        return false;
    }

    UhfFilenameInputCtx ctx = {.dispatcher = dispatcher, .submitted = false};
    text_input_set_header_text(text_input, header);
    text_input_set_minimum_length(text_input, 4U);
    text_input_set_result_callback(text_input, uhf_filename_input_done, &ctx, out, out_size, false);
    view_dispatcher_set_event_callback_context(dispatcher, &ctx);
    view_dispatcher_set_navigation_event_callback(dispatcher, uhf_filename_input_back);
    view_dispatcher_add_view(dispatcher, 0, text_input_get_view(text_input));

    gui_remove_view_port(app->gui, app->view_port);
    view_dispatcher_attach_to_gui(dispatcher, app->gui, ViewDispatcherTypeFullscreen);
    view_dispatcher_switch_to_view(dispatcher, 0);
    view_dispatcher_run(dispatcher);
    view_dispatcher_remove_view(dispatcher, 0);
    view_dispatcher_free(dispatcher);
    text_input_free(text_input);
    gui_add_view_port(app->gui, app->view_port, GuiLayerFullscreen);

    if(!ctx.submitted) return false;
    return uhf_normalize_hex(out, max_hex_len);
}

static bool uhf_save_index_epc_csv(UhfApp* app, const char* filename) {
    if(!app || !filename || !filename[0]) return false;

    char base_name[32];
    uhf_sanitize_filename(filename, base_name, sizeof(base_name));

    char file_name_with_ext[40];
    snprintf(file_name_with_ext, sizeof(file_name_with_ext), "%s.csv", base_name);

    Storage* storage = furi_record_open(RECORD_STORAGE);
    if(!storage) {
        uhf_set_status(app, "Storage unavailable");
        return false;
    }

    if(!storage_dir_exists(storage, UHF_APP_DATA_DIR)) {
        const FS_Error mkdir_result = storage_common_mkdir(storage, UHF_APP_DATA_DIR);
        if(mkdir_result != FSE_OK && mkdir_result != FSE_EXIST) {
            furi_record_close(RECORD_STORAGE);
            uhf_set_status(app, "Create dir failed");
            return false;
        }
    }

    char path[128];
    snprintf(path, sizeof(path), UHF_APP_DATA_DIR "/%s", file_name_with_ext);

    File* file = storage_file_alloc(storage);
    if(!file) {
        furi_record_close(RECORD_STORAGE);
        uhf_set_status(app, "File alloc failed");
        return false;
    }

    bool ok = false;
    do {
        if(!storage_file_open(file, path, FSAM_WRITE, FSOM_CREATE_ALWAYS)) {
            uhf_set_status(app, "Open file failed");
            break;
        }

        const char* header = "index,epc\n";
        if(storage_file_write(file, header, strlen(header)) != strlen(header)) {
            uhf_set_status(app, "Write header failed");
            break;
        }

        if(!uhf_data_lock(app, 50)) {
            uhf_set_status(app, "Busy");
            break;
        }

        size_t index = 1;
        char line[UHF_EPC_HEX_MAX + 32U];
        for(size_t i = 0; i < UHF_MAX_TAGS; i++) {
            if(!app->tags[i].used) continue;

            const int len = snprintf(line, sizeof(line), "%lu,%s\n", (unsigned long)index, app->tags[i].epc);
            if(len <= 0 || (size_t)len >= sizeof(line)) continue;

            if(storage_file_write(file, line, (size_t)len) != (size_t)len) {
                uhf_data_unlock(app);
                uhf_set_status(app, "Write record failed");
                goto save_cleanup;
            }

            index++;
        }
        uhf_data_unlock(app);

        storage_file_sync(file);
        uhf_set_status(app, "Saved CSV: %s", file_name_with_ext);
        if(app->notifications) {
            notification_message(app->notifications, &sequence_success);
        }
        ok = true;
    } while(false);

save_cleanup:
    storage_file_close(file);
    storage_file_free(file);
    furi_record_close(RECORD_STORAGE);
    return ok;
}

static size_t uhf_count_tags(UhfApp* app) {
    if(!app) return 0;
    if(!uhf_data_lock(app, 20)) return 0;

    size_t total = 0;
    for(size_t i = 0; i < UHF_MAX_TAGS; i++) {
        if(!app->tags[i].used) continue;
        total++;
    }

    uhf_data_unlock(app);
    return total;
}

static bool uhf_copy_tag_at(UhfApp* app, size_t wanted, UhfTagEntry* out) {
    if(!app || !out || !uhf_data_lock(app, 20U)) return false;

    size_t index = 0U;
    bool found = false;
    for(size_t i = 0U; i < UHF_MAX_TAGS; i++) {
        if(!app->tags[i].used) continue;
        if(index++ == wanted) {
            *out = app->tags[i];
            found = true;
            break;
        }
    }
    uhf_data_unlock(app);
    return found;
}

static void uhf_move_list_selection(UhfApp* app, bool down) {
    if(!app) return;

    size_t total = uhf_count_tags(app);
    if(total == 0) {
        app->list_selected_index = 0;
        app->list_top_index = 0;
        app->list_selection_manual = false;
        uhf_set_status(app, "No tags yet");
        return;
    }

    if(!app->list_selection_manual) {
        if(app->inventory_running) {
            uhf_stop_inventory(app);
            furi_delay_ms(UHF_STOP_SETTLE_MS);
            uhf_process_rx(app);
            total = uhf_count_tags(app);
        }
        app->list_selection_manual = true;
        app->list_selected_index = down ? 0U : (total - 1U);
        if(app->list_selected_index >= UHF_LIST_VISIBLE_ROWS) {
            app->list_top_index = app->list_selected_index - UHF_LIST_VISIBLE_ROWS + 1U;
        } else {
            app->list_top_index = 0U;
        }
        uhf_set_status(
            app,
            "Tag %lu/%lu",
            (unsigned long)(app->list_selected_index + 1U),
            (unsigned long)total);
        return;
    }

    if(app->list_selected_index >= total) {
        app->list_selected_index = total - 1U;
    }

    if(down) {
        app->list_selected_index =
            app->list_selected_index + 1U < total ? app->list_selected_index + 1U : 0U;
    } else {
        app->list_selected_index =
            app->list_selected_index > 0U ? app->list_selected_index - 1U : total - 1U;
    }

    if(app->list_selected_index < app->list_top_index) {
        app->list_top_index = app->list_selected_index;
    } else if(app->list_selected_index >= app->list_top_index + UHF_LIST_VISIBLE_ROWS) {
        app->list_top_index = app->list_selected_index - UHF_LIST_VISIBLE_ROWS + 1U;
    }

    uhf_set_status(
        app,
        "Tag %lu/%lu",
        (unsigned long)(app->list_selected_index + 1U),
        (unsigned long)total);
}

static void uhf_toggle_inventory_with_cooldown(UhfApp* app) {
    if(!app) return;

    const uint32_t now = furi_get_tick();
    if((now - app->last_inv_cmd_tick) < UHF_INV_CMD_COOLDOWN_MS) {
        uhf_set_status(app, "Inventory cooldown");
        return;
    }
    app->last_inv_cmd_tick = now;

    if(app->inventory_running) {
        uhf_stop_inventory(app);
        uhf_set_status(app, "Inventory stopped");
    } else {
        uhf_start_inventory(app);
    }
}

static void uhf_enter_about_page(UhfApp* app) {
    if(!app) return;

    app->about_return_page = app->page;
    app->about_top_line = 0;
    app->page = UhfPageAbout;
    uhf_set_status(app, "About");
}

