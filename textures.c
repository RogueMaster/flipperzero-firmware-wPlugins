#include "maze3d.h"

// 8x8 单色贴图, 每行1字节(LSB=最左像素), 共8字节/贴图
// 1=实心(亮), 0=空(暗)
// 索引: 0=砖 1=石 2=金属 3=藤蔓 4=水 5=草 6=木 7=树 8=沙
// v6.0: 扩展到 9 张贴图, 覆盖 MC 模式所有方块
const uint8_t TEXTURES[TEX_COUNT][8] = {
    // 0 砖墙: 跑步砌法(错半砖), 横向灰浆床 + 错位竖缝
    {0xFF,0x81,0x7B,0x7B,0xFF,0x81,0xDE,0xDE},
    // 1 石墙: 圆润卵石, 暗缝分隔
    {0x3C,0x7E,0xDB,0xBD,0x66,0xBD,0x7E,0x3C},
    // 2 金属墙: 嵌板 + 四角铆钉 + 中部螺栓
    {0x81,0x42,0x3C,0xA5,0xA5,0x3C,0x42,0x81},
    // 3 藤蔓墙: 有机叶须缠绕
    {0x66,0xA5,0x99,0x5A,0xDB,0x42,0xBD,0xDB},
    // 4 水: 水平波纹 (动态感由 shading 提供)
    {0x00,0x18,0x3C,0x00,0x3C,0x18,0x00,0x66},
    // 5 草地: 短草丛 (顶部密, 底部疏)
    {0xAA,0x55,0xAA,0x44,0x28,0x10,0x44,0x28},
    // 6 木板: 垂直木纹 + 横向拼接缝
    {0x6D,0x5B,0x6D,0xFF,0x6D,0x5B,0x6D,0xFF},
    // 7 树: 树皮纹理 (纵向条纹 + 节疤)
    {0x92,0x55,0xAA,0x92,0x55,0xAA,0x92,0x55},
    // 8 沙: 颗粒点阵
    {0x88,0x22,0x88,0x22,0x44,0x11,0x44,0x11},
};

// 取贴图像素 (1=亮 0=暗)
uint8_t texture_sample(int tex_id, int tx, int ty) {
    if(tex_id < 0 || tex_id >= TEX_COUNT) return 1;
    tx &= 7;
    ty &= 7;
    return (TEXTURES[tex_id][ty] >> (tx & 7)) & 1;
}
